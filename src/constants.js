/**
 * 全部数值常量（0.16.96 起集中到这一处）。
 *
 * 为什么必须放在一起：采样周期（SAMPLE_MS）和切歌窗口（AHEAD_SEC）**是同两个数字**，
 * 一个决定「多久看一次」，一个决定「还剩多少秒动手」。它们分散在 listening.js 与
 * chain.js 时，0.16.93（v111）那次就是采样 10 秒、窗口 10 秒，整段窗口被跳过，
 * 「已经播报了下一首」却一次都没投出去，用户看到的是「报了没放」。
 *
 * 规矩：
 *   1. 任何模块要调这些数，一律 import，不许就地再写一个同义常量。
 *   2. 改这里的任何一个数，必须顺手看 SAMPLE_MS 与 AHEAD_SEC 的关系：
 *      理想是 AHEAD_SEC ≥ 2 个采样周期（窗口里至少两次机会）。
 *      **现状：SAMPLE_MS = 10 秒、AHEAD_SEC = 10 秒，只有 1 个周期** ——
 *      这是老的 3 秒采样遗留下来的关系；要动切歌窗口请连采样一起验，别只改一个。
 *   3. 这里的数只描述「本机自己的节拍」，等外部回话的耐心放在 adapters 的超时里，
 *      两者不要混。
 */

/** 采样间隔：每 10 秒读一次播放条。 */
export const SAMPLE_MS = 10_000;

/** 连续读不到客户端时放慢到这个间隔。 */
export const IDLE_MS = 30_000;

/** 连续读不到多少次才判「停了」（3 次约 30 秒，避免标题闪空把一首劈成两段）。 */
export const MISS_TO_CLOSE = 3;

/** 一段听满这么久才算一次收听。 */
export const MIN_SEC = 20;

/** 单段最长 5 分钟：单曲循环会被切成两段，等于又听了一遍。 */
export const SEG_MAX_SEC = 300;

/** 三张卡的触发时长：30 / 60 / 90 秒。 */
export const SAY_AFTER_SEC = 30;
export const LIKE_AFTER_SEC = 60;
export const COMMENT_AFTER_SEC = 90;

/** 真要开口前再确认一次没切歌（毫秒）。 */
export const CONFIRM_MS = 4000;

/** 播报窗口宽度（秒）：这一遍落到「阈值 ~ 阈值 + 这个值」才开口，宽一点才不漏。 */
export const GATE_WIN_SEC = 25;

/** 进度往回跳超过这么多秒，判成「又放了一遍」。 */
export const REWIND_SEC = 5;

/** 安静判定：连续没放歌多久算安静；提过一次后隔多久再提。 */
export const IDLE_MIN_SEC = 60;
export const IDLE_REPEAT_DEFAULT_SEC = 3600;

/**
 * 接力：剩多少秒播报、剩多少秒切、投完多久核对、承诺有效期。
 * 下面这四个与 SAMPLE_MS 的关系见文件头。
 */
export const AHEAD_SEC = 10;
export const SAY_AHEAD_SEC = 30;
export const VERIFY_WAIT_MS = 30 * 1000;
export const PROMISE_TTL_MS = 5 * 60 * 1000;

/** 一轮接力的整体有效期与预告过期时间（chain.js 内部用，一并放这里备查）。 */
export const CHAIN_TTL_MS = 90 * 60 * 1000;
export const PREVIEW_STALE_MS = 20 * 60 * 1000;

/**
 * 0.17.43（A8）：用户动作（点歌 / 手动切歌 / 换来源）之后的接力静默期。
 * 这 45 秒里闸门只看不动 —— 覆盖「快慢路径 1.4~10 秒起播 + 播放条换标题」那段，
 * 也覆盖「手动切歌后客户端还在切」的几秒。要调就改这一个数。
 */
export const USER_ACTION_HOLD_MS = 45 * 1000;

